"""Write or check docs/traceability.md: FT id -> tests | manual | pending.

Active ids come from `- **FT-...**` lines in docs/spec/NN-*.md; struck-through
ids (`- ~~**FT-...**~~`) are removed and excluded (FT-TST-015). Tests name the
ids they verify on `# FT: <ids>` comment lines in .gd and .py files under
tests/ and tools/tests/ (fixtures excluded) (FT-TST-016). Ids verified by a
playtest or owner step are listed with an issue link in
docs/traceability-manual.md (FT-TST-017). An entry marked `(owner-judged)` right after
the id is a target the owner judges from a report: it shows `manual` even when a test
reports on it (D252); other entries show `manual` only for ids with no test.

Usage: traceability.py [--check]
"""

import re
import sys
from pathlib import Path

ID = r"FT-[A-Z0-9]+-\d+"
ACTIVE = re.compile(rf"^- \*\*({ID})\*\*", re.M)
REMOVED = re.compile(rf"^- ~~\*\*({ID})\*\*~~", re.M)
TAG = re.compile(r"^\s*#\s*FT:(.*)$", re.M)
MANUAL = re.compile(rf"^- ({ID})\b(.*)$", re.M)
JUDGED = "(owner-judged)"
LINK = re.compile(r"https://github\.com/[\w.-]+/[\w.-]+/issues/\d+|(?:[\w.-]+/[\w.-]+)?#\d+")
OUT = "docs/traceability.md"


def spec_ids(root: Path) -> tuple[list[str], set[str]]:
    active: list[str] = []
    removed: set[str] = set()
    for f in sorted((root / "docs/spec").glob("[0-9]*.md")):
        text = f.read_text()
        active += ACTIVE.findall(text)
        removed |= set(REMOVED.findall(text))
    return active, removed


def tagged_tests(root: Path) -> tuple[dict[str, list[str]], list[str]]:
    tags: dict[str, list[str]] = {}
    errors: list[str] = []
    for base in ("tests", "tools/tests"):
        for f in sorted((root / base).rglob("*")):
            rel = f.relative_to(root).as_posix()
            if f.suffix not in (".gd", ".py") or rel.startswith("tools/tests/fixtures/"):
                continue
            for line in TAG.findall(f.read_text()):
                ids = re.findall(ID, line)
                if not ids:
                    errors.append(f"{rel}: '# FT:' tag names no id")
                for i in ids:
                    if rel not in tags.setdefault(i, []):
                        tags[i].append(rel)
    return tags, errors


def manual_ids(root: Path) -> tuple[dict[str, str], set[str], list[str]]:
    f = root / "docs/traceability-manual.md"
    manual: dict[str, str] = {}
    judged: set[str] = set()
    errors: list[str] = []
    for i, rest in MANUAL.findall(f.read_text() if f.exists() else ""):
        link = LINK.search(rest)
        if link:
            manual[i] = link.group(0)
            if rest.lstrip().startswith(JUDGED):
                judged.add(i)
        else:
            errors.append(f"docs/traceability-manual.md: {i} has no issue link")
    return manual, judged, errors


def render(
    active: list[str], tags: dict[str, list[str]], manual: dict[str, str], judged: set[str]
) -> str:
    rows = []
    counts = {"tests": 0, "manual": 0, "pending": 0}
    for i in active:
        if i in judged:
            status = "manual"
        else:
            status = "tests" if i in tags else "manual" if i in manual else "pending"
        counts[status] += 1
        by = [f"`{t}`" for t in tags.get(i, [])]
        if i in manual:
            link = manual[i]
            by.append(f"[#{link.rsplit('/', 1)[-1]}]({link})" if link.startswith("http") else link)
        rows.append(f"| {i} | {status} | {', '.join(by)} |")
    return "\n".join([
        "# Traceability",
        "",
        "Generated by `tools/traceability.py` from the active ids in `docs/spec/`, the `# FT:`"
        " tags in `tests/` and `tools/tests/` (see `tests/README.md`) and"
        " `docs/traceability-manual.md`. Don't edit it by hand: rerun the script (FT-TST-015).",
        "",
        f"Tests: {counts['tests']}, manual: {counts['manual']}, pending: {counts['pending']}.",
        "",
        "| Id | Status | Verified by |",
        "|---|---|---|",
        *rows,
        "",
    ])


def run(root: Path, check: bool) -> list[str]:
    active, removed = spec_ids(root)
    tags, errors = tagged_tests(root)
    manual, judged, manual_errors = manual_ids(root)
    errors += manual_errors
    known = set(active)
    for source, ids in (("test tag", tags), ("manual entry", manual)):
        for i in ids:
            if i in removed:
                errors.append(f"{source} names removed id {i}")
            elif i not in known:
                errors.append(f"{source} names unknown id {i}")
    text = render(active, tags, manual, judged)
    out = root / OUT
    if check:
        if not out.exists() or out.read_text() != text:
            errors.append(f"{OUT} is stale: run tools/traceability.py")
    else:
        out.write_text(text)
    return errors


def main(argv: list[str]) -> int:
    root = Path(__file__).resolve().parent.parent
    errors = run(root, "--check" in argv)
    for e in errors:
        print(f"traceability: {e}", file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
